/** IST wall-clock time on the IST day that contains `day`. */
const at = (day: Date, hours: number, minutes = 0) => new Date(Date.parse(`${istDay(day)}T00:00:00.000Z`) - IST + (hours * 60 + minutes) * 60_000);
const isFriday = (day: Date) => new Date(`${istDay(day)}T00:00:00.000Z`).getUTCDay() === 5;

export async function seedIfEmpty() {
  if (await Staff.estimatedDocumentCount()) return false;
  await seed();
  return true;
}

export async function seed(now = new Date()) {
  const started = Date.now();
  const settings = await getSettings();
  const passwordHash = await bcrypt.hash(DEMO_PASSWORD, 10);

  // ---------- People ----------
  const staff = await Staff.create(STAFF.map((s) => ({ ...s, passwordHash })));
  const actorFor = (role: 'ops' | 'finance' | 'admin'): Actor => {
    const s = staff.find((x) => x.role === role)!;
    return { type: 'staff', id: String(s._id), name: s.name };
  };
  const opsActor = actorFor('ops');
  const financeActor = actorFor('finance');

  const partners = new Map<string, { id: Types.ObjectId; seed: PartnerSeed }>();
  for (const p of PARTNERS) {
    const joined = new Date(now.getTime() - p.joinedDaysAgo * DAY - Math.floor(rand() * 8) * 3_600_000);
    const doc = await Affiliate.create({
      name: p.name,
      email: p.email,
      phone: `+91${p.phone}`,
      passwordHash,
      code: p.code,
      audience: p.audience,
      city: p.city,
      instagram: p.instagram,
      emailFp: fingerprint(p.email),
      phoneFp: fingerprint(p.phone),
      payoutMethod: p.upi
        ? { kind: 'upi', upiId: p.upi, updatedAt: joined }
        : p.bank
          ? { kind: 'bank', accountName: p.bank.accountName, accountNumberEnc: encrypt(p.bank.accountNumber), accountNumberLast4: p.bank.accountNumber.slice(-4), ifsc: p.bank.ifsc, updatedAt: joined }
          : null,
      panEnc: p.pan ? encrypt(p.pan) : null,
      panLast4: p.pan ? p.pan.slice(-4) : null,
    });
    // createdAt is immutable through Mongoose; backdate it with the driver.
    await Affiliate.collection.updateOne({ _id: doc._id }, { $set: { createdAt: joined, updatedAt: joined } });
    await record({
      at: joined,
      actor: { type: 'affiliate', id: String(doc._id), name: p.name },
      action: 'affiliate.joined',
      entity: 'affiliate',
      entityId: String(doc._id),
      summary: `${p.name} joined as a ${p.audience} partner with code ${p.code}`,
    });
    partners.set(p.code, { id: doc._id, seed: p });
  }

  // ---------- Orders over the last 60 days ----------
  type Planned = IncomingOrder & { refundAfterDays?: number; refundShare?: number };
  const planned: Planned[] = [];
  let orderNo = 48_210;
  const customers = Array.from({ length: 140 }, (_, i) => `shopper${i + 1}@example.com`);

  const makeOrder = (code: string, placedAt: Date, opts: { items?: { p: (typeof PRODUCTS)[number]; qty: number }[]; email?: string } = {}): Planned => {
    const items = opts.items ?? (rand() < 0.22 ? [{ p: pick(PRODUCTS), qty: 1 }, { p: pick(PRODUCTS), qty: 1 }] : [{ p: rand() < 0.45 ? PRODUCTS[0] : pick(PRODUCTS), qty: 1 }]);
    const subtotal = items.reduce((s, i) => s + i.p.price * i.qty, 0);
    const discount = Math.round((subtotal * settings.customerDiscountPct) / 100);
    return {
      id: `CA-${orderNo++}`,
      placedAt,
      code,
      customer: { email: opts.email ?? pick(customers) },
      items: items.map((i) => ({ sku: i.p.sku, name: i.p.name, qty: i.qty, price: i.p.price })),
      subtotal,
      discount,
      shipping: 0,
      tax: 0,
      total: subtotal - discount,
    };
  };

  for (const { seed: p } of partners.values()) {
    const activeDays = Math.min(p.joinedDaysAgo, 60);
    const expected = Math.round(activeDays * p.weight * 0.075);
    for (let i = 0; i < expected; i++) {
      const daysAgo = rand() * (activeDays - 0.3);
      const placedAt = new Date(now.getTime() - daysAgo * DAY);
      planned.push(makeOrder(p.code, placedAt));
    }
  }

  // Story beats the walkthrough relies on:
  const daysAgo = (d: number, h = 0) => new Date(now.getTime() - d * DAY - h * 3_600_000);
  // A fresh order for Priya, so her home screen shows something on hold.
  planned.push(makeOrder('PRIYA10', daysAgo(0, 3)));
  planned.push(makeOrder('PRIYA10', daysAgo(1, 2), { items: [{ p: PRODUCTS[1], qty: 1 }, { p: PRODUCTS[2], qty: 1 }] }));
  // Priya: an order returned within the window → reversed.
  planned.push({ ...makeOrder('PRIYA10', daysAgo(9)), refundAfterDays: 3 });
  // Ananya: refunded after it had been paid out → clawback on her next payout.
  planned.push({ ...makeOrder('PRANASTUDIO', daysAgo(38), { items: [{ p: PRODUCTS[0], qty: 2 }] }), refundAfterDays: 27 });
  // Tanvi: one of two items returned while on hold → commission reduced.
  planned.push({ ...makeOrder('TANVIFLOW', daysAgo(6), { items: [{ p: PRODUCTS[3], qty: 1 }, { p: PRODUCTS[1], qty: 1 }] }), refundAfterDays: 2, refundShare: 1_699 / (1_799 + 1_699) });
  // Needs review: Rahul bought with his own code.
  planned.push(makeOrder('RAHULYOGA', daysAgo(4, 5), { email: 'rahul@partners.demo' }));
  // Needs review: a bulk studio order above the review limit.
  planned.push(makeOrder('ASHTANGAGGN', daysAgo(3, 1), { items: [{ p: PRODUCTS[0], qty: 8 }] }));
  // Needs review: the same shopper using one code again and again.
  for (const d of [26, 19, 11, 2]) planned.push(makeOrder('MEHERMOVES', daysAgo(d, 4), { email: 'repeat.buyer@example.com' }));
  // Vikram: self-referrals that get rejected, then his account is paused.
  planned.push(makeOrder('VIKRAMYOGA', daysAgo(21), { email: 'vikram@partners.demo' }));
  planned.push(makeOrder('VIKRAMYOGA', daysAgo(20), { email: 'vikram@partners.demo' }));
  // Kabir has earnings but no payout details → blocked in finance's preview.
  planned.push(makeOrder('KABIRPHYSIO', daysAgo(22)));
  planned.push(makeOrder('KABIRPHYSIO', daysAgo(19)));

  planned.sort((a, b) => a.placedAt.getTime() - b.placedAt.getTime());
  // Renumber chronologically so order ids read naturally.
  planned.forEach((o, i) => (o.id = `CA-${48_210 + i}`));

  // ---------- Replay the timeline day by day ----------
  const refunds: { at: Date; id: string; amount: number }[] = [];
  const startDay = addDays(now, -61);
  let lastFriday = '';
  for (let d = 0; d <= 61; d++) {
    const day = addDays(startDay, d);
    if (isFriday(day) && at(day, 16) < now) lastFriday = istDay(day);
  }
  // Last Friday's batch is left mid-reconciliation for the demo: one transfer bounced
  // (account closed) and two payments are still waiting for their UTR from the bank.
  let cursor = 0;

  for (let d = 0; d <= 61; d++) {
    const day = addDays(startDay, d);
    const dayEnd = d === 61 ? now : at(day, 23, 59);

    // The release job, early each morning.
    const morning = at(day, 6);
    if (morning < now) await releaseDue(morning);

    // Friday payout run for everything that's ready.
    if (isFriday(day) && at(day, 16) < now) {
      const ready = await Commission.distinct('affiliateId', { status: 'approved' });
      if (ready.length) {
        try {
          const batch = await createBatch({ affiliateIds: ready.map(String), actor: financeActor, now: at(day, 11) });
          const isLast = istDay(day) === lastFriday;
          // Priya (the demo partner) is always paid; of the others, a bank transfer bounces
          // and up to two payments wait for their UTR.
          const others = batch.items.filter((i) => i.code !== 'PRIYA10');
          const bounced = isLast ? others.find((i) => i.method.kind === 'bank') : undefined;
          const awaiting = new Set(isLast ? others.filter((i) => i !== bounced).slice(0, 2).map((i) => i.code) : []);
          for (const item of batch.items) {
            if (awaiting.has(item.code)) continue;
            if (item === bounced) {
              await markItemFailed({ payoutId: String(batch._id), itemId: String(item._id), reason: 'Bank returned the transfer: account closed', actor: financeActor, now: at(day, 18) });
              continue;
            }
            const utr = item.method.kind === 'upi' ? digits(12) : `${(item.method.ifsc ?? 'HDFC').slice(0, 4)}N${istDay(day).slice(2, 4)}${digits(9)}`;
            await markItemPaid({ payoutId: String(batch._id), itemId: String(item._id), utr, actor: financeActor, now: at(day, 16, Math.floor(rand() * 50)) });
          }
        } catch (err) {
          if ((err as { status?: number }).status !== 409) throw err; // nothing eligible yet
        }
      }
    }

    // Orders placed today.
    while (cursor < planned.length && planned[cursor].placedAt <= dayEnd) {
      const o = planned[cursor++];
      await ingestOrder(o, { now: new Date(o.placedAt.getTime() + 60_000) });
      if (o.refundAfterDays) {
        const amount = o.refundShare ? Math.round(o.total * o.refundShare) : o.total;
        refunds.push({ at: addDays(o.placedAt, o.refundAfterDays), id: o.id, amount });
      }
    }

    // Refunds the store reported today.
    for (const r of refunds.filter((x) => x.at <= dayEnd && x.at > addDays(dayEnd, -1))) {
      await ingestRefund({ id: r.id, refundedAmount: r.amount }, { now: r.at });
    }

    // Share-link clicks.
    for (const { id, seed: p } of partners.values()) {
      if (p.joinedDaysAgo < 61 - d) continue;
      const clicks = Math.round(p.weight * (2 + rand() * 6));
      if (clicks) await ClickDay.updateOne({ affiliateId: id, day: istDay(day) }, { $inc: { count: clicks } }, { upsert: true });
    }
  }

  // ---------- Reviews and account actions ----------
  const vikram = partners.get('VIKRAMYOGA')!;
  const vikramFlagged = await Commission.find({ affiliateId: vikram.id, status: 'pending', 'flags.0': { $exists: true } }, { _id: 1 }).lean();
  if (vikramFlagged.length) {
    await reviewCommissions({ ids: vikramFlagged.map((c) => c._id), decision: 'reject', note: 'Orders placed with the partner’s own email', actor: opsActor, now: daysAgo(17) });
  }
  await setAffiliateStatus(String(vikram.id), 'suspended', opsActor);

  // The scheduled job would have run this morning.
  await releaseDue(now);

  logger.info('Seeded demo data', {
    partners: partners.size,
    orders: planned.length,
    payouts: await Payout.countDocuments(),
    ms: Date.now() - started,
  });
}
